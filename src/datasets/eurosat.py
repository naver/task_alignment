# Class names as published by OpenAI for CLIP:
#   https://github.com/openai/CLIP/blob/main/data/prompts.md (MIT)
import os
import re

import torchvision.datasets as datasets

from .base import BaseDataset

# EuroSAT ships one directory per class. The label strings below are the
# prompt-friendly EuroSAT class names published by OpenAI for CLIP, see
# https://github.com/openai/CLIP/blob/main/data/prompts.md (MIT licensed).
CLIP_CLASSNAMES = {
    "annualcrop": "annual crop land",
    "forest": "forest",
    "herbaceousvegetation": "brushland or shrubland",
    "highway": "highway or road",
    "industrial": "industrial buildings or commercial buildings",
    "pasture": "pasture land",
    "permanentcrop": "permanent crop land",
    "residential": "residential buildings or homes or apartments",
    "river": "river",
    "sealake": "lake or sea",
}


def clip_classname(directory_name: str) -> str:
    """Return the CLIP prompt label for one EuroSAT class directory.

    Directory names are matched case-insensitively and ignoring any separators,
    so `AnnualCrop`, `annual_crop` and `Annual Crop` all resolve alike.
    """
    key = re.sub(r"[^a-z]", "", directory_name.lower())
    if key not in CLIP_CLASSNAMES:
        raise KeyError(
            f"Unrecognised EuroSAT class directory {directory_name!r}; "
            f"expected one of {sorted(CLIP_CLASSNAMES)}."
        )
    return CLIP_CLASSNAMES[key]


class EuroSAT(BaseDataset):
    """EuroSAT read from pre-split ``EuroSAT_splits/<split>/<class>/`` folders.

    Unlike most wrappers here the validation split is a real directory on disk
    rather than a subsample of train, so `EuroSATVal` overrides the test split
    instead of being generated by the registry.
    """

    data_subdir = "EuroSAT_splits"
    train_kwargs = {"split": "train"}
    test_kwargs = {"split": "test"}

    def build_dataset(self, root, preprocess, split_kwargs):
        return datasets.ImageFolder(
            os.path.join(root, split_kwargs["split"]), transform=preprocess
        )

    def get_classnames(self):
        # ImageFolder orders classes alphabetically; recover that order and turn
        # each directory name into the label CLIP was prompted with.
        mapping = self.train_dataset.class_to_idx
        return [clip_classname(n) for n in sorted(mapping, key=mapping.get)]


class EuroSATVal(EuroSAT):
    test_kwargs = {"split": "val"}
